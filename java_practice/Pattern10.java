class Pattern10 
{
	public static void main(String[] args) 
	{
		for (int a=1;a<=5 ;a++ )
	    {
		   System.out.print(" "+a+" ");
	    }
		System.out.println();
		for (char b='a';b<='d' ;b++ )
		{
          System.out.print(" "+b+" ");
		}
		System.out.println();
		for (int c=0;c<=4 ;c++ )
	    {
			if (c%2==0)
			{
				System.out.print(" "+c+" ");
			}
	    }
		System.out.println();
	}
}
